"use client";

import { WriteButton } from "@/app/RoleControls";

import { useEffect, useRef, useState } from "react";
import type { PreMeetingBriefView } from "@/lib/services/setupAnalystService";

type Status = "idle" | "generating" | "success" | "error";

const SUCCESS_MESSAGE_MS = 3000;

function ConfidenceBadge({ level }: { level: string }) {
  return (
    <span className="rounded-full border border-neutral-300 px-2 py-0.5 text-xs font-medium capitalize dark:border-neutral-700">
      {level}
    </span>
  );
}

function PriorityBadge({ priority }: { priority: string }) {
  return (
    <span className="rounded-full border border-neutral-300 px-2 py-0.5 text-xs font-medium capitalize text-neutral-500 dark:border-neutral-700">
      {priority}
    </span>
  );
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div>
      <h3 className="text-sm font-semibold uppercase tracking-wide text-neutral-500">{title}</h3>
      <div className="mt-1">{children}</div>
    </div>
  );
}

export default function GenerateBriefSection({
  meetingId,
  initialBriefView,
}: {
  meetingId: string;
  initialBriefView: PreMeetingBriefView;
}) {
  const [briefView, setBriefView] = useState<PreMeetingBriefView>(initialBriefView);
  const [status, setStatus] = useState<Status>("idle");
  const [error, setError] = useState<string | null>(null);
  const successTimeoutRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    return () => {
      if (successTimeoutRef.current) clearTimeout(successTimeoutRef.current);
    };
  }, []);

  async function handleGenerate() {
    setError(null);
    setStatus("generating");
    try {
      const response = await fetch(`/api/meetings/${meetingId}/generate-brief`, {
        method: "POST",
      });
      const result = await response.json();

      if (!response.ok) {
        throw new Error(result.error ?? "Failed to generate brief");
      }

      setBriefView(result as PreMeetingBriefView);
      setStatus("success");
      successTimeoutRef.current = setTimeout(() => setStatus("idle"), SUCCESS_MESSAGE_MS);
    } catch (err) {
      setStatus("error");
      setError(err instanceof Error ? err.message : "Failed to generate brief");
    }
  }

  const { brief, hypotheses, assumptions, initialQueue } = briefView;
  const generating = status === "generating";

  return (
    <section className="rounded border border-neutral-200 bg-white p-4 dark:border-neutral-800 dark:bg-neutral-900">
      <div className="flex items-center justify-between gap-3">
        <div>
          <h2 className="text-sm font-semibold uppercase tracking-wide text-neutral-500">
            Discovery brief
          </h2>
          <p className="mt-1 text-xs text-neutral-500">
            Generated by the Setup Analyst. Treats your tentative build direction as a
            hypothesis to challenge, not a done deal.
          </p>
        </div>
        <WriteButton
          onClick={handleGenerate}
          disabled={generating}
          className="shrink-0 rounded bg-neutral-900 px-4 py-2 text-sm font-medium text-white disabled:opacity-50 dark:bg-neutral-100 dark:text-neutral-900"
        >
          {generating
            ? "Generating..."
            : brief
              ? "Regenerate Brief"
              : "Generate Discovery Brief"}
        </WriteButton>
      </div>

      {status === "success" && (
        <p className="mt-2 text-sm text-green-600 dark:text-green-400">
          Brief generated.
        </p>
      )}
      {status === "error" && error && (
        <div className="mt-2 rounded border border-red-300 bg-red-50 p-3 dark:border-red-900 dark:bg-red-950">
          <p className="text-sm text-red-700 dark:text-red-400">
            Meeting saved, but brief generation failed. Try again.
          </p>
          <p className="mt-1 text-xs text-red-600 dark:text-red-500">{error}</p>
        </div>
      )}

      {brief ? (
        <div className="mt-4 space-y-5">
          {brief.build_direction_warning && (
            <div className="rounded border border-amber-300 bg-amber-50 p-3 dark:border-amber-800 dark:bg-amber-950">
              <h3 className="text-xs font-semibold uppercase tracking-wide text-amber-700 dark:text-amber-400">
                Build direction warning
              </h3>
              <p className="mt-1 text-sm text-amber-800 dark:text-amber-300">
                {brief.build_direction_warning}
              </p>
            </div>
          )}

          <Section title="Brief summary">
            <p className="whitespace-pre-wrap text-sm">{brief.brief_summary}</p>
          </Section>

          <Section title="Suggested opening">
            <p className="whitespace-pre-wrap text-sm italic">&ldquo;{brief.suggested_opening}&rdquo;</p>
          </Section>

          <Section title="Recommended focus">
            <p className="whitespace-pre-wrap text-sm">{brief.recommended_focus}</p>
          </Section>

          <Section title="Must learn">
            <ul className="list-disc space-y-1 pl-5 text-sm">
              {brief.must_learn.map((item, i) => (
                <li key={i}>{item}</li>
              ))}
            </ul>
          </Section>

          <Section title="Initial hypotheses">
            {hypotheses.length > 0 ? (
              <ul className="space-y-1">
                {hypotheses.map((h) => (
                  <li key={h.id} className="flex items-start gap-2 text-sm">
                    <ConfidenceBadge level={h.confidence_level} />
                    <span>{h.statement}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-neutral-400">None generated.</p>
            )}
          </Section>

          <Section title="Assumptions to validate">
            {assumptions.length > 0 ? (
              <ul className="space-y-1">
                {assumptions.map((a) => (
                  <li key={a.id} className="flex items-start gap-2 text-sm">
                    <ConfidenceBadge level={a.confidence_level} />
                    <span>{a.text}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-neutral-400">None recorded.</p>
            )}
          </Section>

          <Section title="Risk focus">
            <ul className="list-disc space-y-1 pl-5 text-sm">
              {brief.risk_focus.map((item, i) => (
                <li key={i}>{item}</li>
              ))}
            </ul>
          </Section>

          <Section title="Initial queue">
            {initialQueue.length > 0 ? (
              <ul className="space-y-2">
                {initialQueue.map((thread) => (
                  <li
                    key={thread.id}
                    className="rounded border border-neutral-200 p-2 text-sm dark:border-neutral-800"
                  >
                    <div className="flex items-center justify-between">
                      <span className="font-medium">{thread.title}</span>
                      <PriorityBadge priority={thread.priority} />
                    </div>
                    {thread.why_it_matters && (
                      <p className="mt-1 text-xs italic text-neutral-500">
                        {thread.why_it_matters}
                      </p>
                    )}
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-neutral-400">No queue generated.</p>
            )}
          </Section>

          {brief.applied_ai_brief && (
            <div className="space-y-4 rounded border border-dashed border-neutral-300 p-3 dark:border-neutral-700">
              <h3 className="text-xs font-semibold uppercase tracking-widest text-neutral-400">
                Applied AI Discovery prep
              </h3>

              <Section title="Suspected workflow pain">
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.suspectedWorkflowPain.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>

              <Section title="Likely task / intervention type">
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.likelyTaskInterventionTypes.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>

              <Section title="Data readiness questions">
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.dataReadinessQuestions.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>

              <Section title="Risk / constraint questions">
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.riskConstraintQuestions.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>

              <Section title="Human-review questions">
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.humanReviewQuestions.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>

              <Section title="Implementation-readiness questions">
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.implementationReadinessQuestions.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>

              <Section title="Smallest useful experiment (hypothesis)">
                <p className="text-sm">{brief.applied_ai_brief.smallestUsefulExperimentHypothesis}</p>
              </Section>

              <Section title="No-build / not-ready risk">
                <p className="text-sm">{brief.applied_ai_brief.noBuildNotReadyRisk}</p>
              </Section>

              <Section title="Patterns to validate">
                <p className="mb-1 text-xs text-neutral-500">
                  Hypotheses to go test in conversation, not recommendations.
                </p>
                <ul className="list-disc space-y-1 pl-5 text-sm">
                  {brief.applied_ai_brief.patternsToValidate.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Section>
            </div>
          )}
        </div>
      ) : (
        <p className="mt-4 text-sm text-neutral-400">
          No brief generated yet. Click &ldquo;Generate Discovery Brief&rdquo; to prepare one.
        </p>
      )}
    </section>
  );
}
